/// Why an on-demand core install could not finish. Each value has one plain
/// sentence that the Core Manager shows verbatim — the same words on every
/// screen, with no raw exception text.
enum CoreDownloadFailure {
  noAssetForPlatform,
  unreachable,
  checksumMismatch,
  tooLarge,
  cancelled;

  String get sentence => switch (this) {
    noAssetForPlatform => 'This core is not published for this device.',
    unreachable =>
      'The download could not be reached. Check your connection and try again.',
    checksumMismatch =>
      'The download did not match its checksum and was discarded.',
    tooLarge => 'The download was too large and was refused.',
    cancelled => 'Download cancelled.',
  };
}

/// A download failure with a stable kind for the UI and the exact URLs tried
/// in [detail] for diagnostics. It is a [StateError] so existing callers that
/// treat a refused download as a bad state keep working.
class CoreDownloadException extends StateError {
  CoreDownloadException(this.failure, [this.detail = ''])
    : super(_message(failure, detail));

  final CoreDownloadFailure failure;
  final String detail;

  static String _message(CoreDownloadFailure failure, String detail) =>
      detail.isEmpty ? failure.sentence : '${failure.sentence} $detail';
}

/// A non-200 response from the asset host. Keeping the status code typed lets
/// the downloader recognise a stale manifest (404) without parsing prose.
class CoreAssetHttpException implements Exception {
  const CoreAssetHttpException(this.statusCode, this.url);

  final int statusCode;
  final Uri url;

  @override
  String toString() => 'HTTP $statusCode fetching $url';
}

/// Cancellation token owned by the caller and polled while bytes stream in.
/// A cancelled download is refused through [CoreDownloadFailure.cancelled]
/// and leaves no partial file behind.
class CoreDownloadCancel {
  bool _cancelled = false;

  bool get isCancelled => _cancelled;

  void reset() => _cancelled = false;

  void cancel() => _cancelled = true;
}

/// The repository whose releases host on-demand core assets today.
const String kCurrentCoreRepo = '0xJ1nn/ezcore';

/// Earlier owner handle for the same repository (`JinUltimate1995`).
/// Bundled release manifests from before the rename still carry it, so their
/// asset URLs now 404. Stored lowercase for comparison with normalized input.
const Set<String> kLegacyCoreRepoOwners = {'jinultimate1995'};

/// Where on-demand core assets live — parsed from `cores/release.json`
/// (regenerated by `scripts/build_catalog.py`): the GitHub release tag
/// matching this build's pubspec version plus the asset file name for
/// every `delivery: download` core that has a pin for that platform.
///
/// This is the whole trust story (hybrid core delivery): the app fetches exactly these
/// names, from exactly this tag, and verifies the bytes against the pin
/// that ships inside the same catalog it already trusts.
class CoreRelease {
  const CoreRelease({
    required this.repo,
    required this.tag,
    required this.assets,
    this.unavailablePlatforms = const {},
  });

  /// `owner/name` of the repository whose releases host the core assets.
  final String repo;

  /// Release tag (e.g. `v0.2.0`) — pins in this build's catalog came from
  /// the same version.
  final String tag;

  /// platform-arch key -> core id -> asset file name.
  final Map<String, Map<String, String>> assets;

  /// platform-arch key -> plain reason that platform publishes no assets.
  /// Generated by `scripts/build_catalog.py` for every platform the release
  /// script can build, so an absent platform is never a silent omission.
  final Map<String, String> unavailablePlatforms;

  factory CoreRelease.fromJson(Map<String, dynamic> json) {
    final assets = <String, Map<String, String>>{};
    final raw = json['assets'];
    if (raw is Map) {
      for (final entry in raw.entries) {
        final inner = <String, String>{};
        if (entry.value is Map) {
          entry.value.forEach((k, v) => inner[k.toString()] = v.toString());
        }
        assets[entry.key.toString()] = inner;
      }
    }
    final unavailable = <String, String>{};
    final rawUnavailable = json['unavailablePlatforms'];
    if (rawUnavailable is Map) {
      for (final entry in rawUnavailable.entries) {
        final value = entry.value;
        final message = value is Map
            ? value['message']?.toString()
            : value?.toString();
        if (message != null && message.isNotEmpty) {
          unavailable[entry.key.toString()] = message;
        }
      }
    }
    return CoreRelease(
      repo: (json['repo'] as String?) ?? '',
      tag: (json['tag'] as String?) ?? '',
      assets: assets,
      unavailablePlatforms: unavailable,
    );
  }

  /// True when the bundled manifest names the repository's former owner.
  bool get usesLegacyOwner => kLegacyCoreRepoOwners.contains(
    repo.split('/').first.toLowerCase(),
  );

  /// Asset file name for [coreId] on [platformKey], or null when nothing
  /// is published for that pair (older catalogs, unbuilt platforms).
  String? assetName(String platformKey, String coreId) =>
      assets[platformKey]?[coreId];

  /// Whether this release publishes any asset for [platformKey].
  bool hasAssetsFor(String platformKey) =>
      (assets[platformKey]?.isNotEmpty ?? false);

  /// Plain reason [platformKey] publishes no on-demand assets, when the
  /// release map says one. Null when the platform is published or unknown.
  String? unavailableMessage(String platformKey) =>
      unavailablePlatforms[platformKey];

  Uri _uri(String ownerRepo, String platformKey, String coreId) {
    final name = assetName(platformKey, coreId);
    if (ownerRepo.isEmpty || tag.isEmpty || name == null) {
      throw CoreDownloadException(
        CoreDownloadFailure.noAssetForPlatform,
        '$coreId is not published for $platformKey (no release asset)',
      );
    }
    return Uri.parse(
      'https://github.com/$ownerRepo/releases/download/$tag/$name',
    );
  }

  /// Full download URL for [coreId] on [platformKey] using the configured
  /// repository. Throws [CoreDownloadException] when no asset is published.
  Uri downloadUri(String platformKey, String coreId) =>
      _uri(repo, platformKey, coreId);

  /// The one retry URL, only for manifests that still name a legacy owner.
  /// Null for current manifests — a 404 there must never be retried against
  /// another repository.
  Uri? fallbackUri(String platformKey, String coreId) =>
      usesLegacyOwner ? _uri(kCurrentCoreRepo, platformKey, coreId) : null;
}

/// Streams one release asset as byte chunks. Implementations surface
/// transport/HTTP failures as errors on the stream (or synchronously).
abstract class CoreAssetFetcher {
  Stream<List<int>> open(Uri url);
}

/// Production fetcher: `dart:io` HTTP with redirect following — GitHub
/// release assets redirect to signed object-storage URLs. No extra
/// dependency; works on every platform that runs the app.
class HttpClientAssetFetcher implements CoreAssetFetcher {
  const HttpClientAssetFetcher();

  @override
  Stream<List<int>> open(Uri url) async* {
    final client = HttpClient()..autoUncompress = false;
    try {
      final request = await client.getUrl(url);
      final response = await request.close();
      if (response.statusCode != HttpStatus.ok) {
        throw CoreAssetHttpException(response.statusCode, url);
      }
      yield* response;
    } finally {
      client.close(force: true);
    }
  }
}

/// Downloads a core on demand into the local vault, byte-verified.
///
/// Contract (nothing on the network is trusted):
/// 1. bytes stream into `<dest>.part` (memory-safe, size-capped);
/// 2. the part file is sha256-verified against the **manifest pin** —
///    the same pin the catalog already ships;
/// 3. only a verified file is renamed into place, with the `.ezpin`
///    sidecar the staging fast path expects;
/// 4. only then is the registry told to install.
///
/// A stale manifest that 404s is retried once against the current repository,
/// but the retry goes through the very same pin gate. Any failure deletes the
/// partial file and throws a [CoreDownloadException]; the registry never
/// learns about unverified bytes.
class CoreDownloader {
  CoreDownloader({
    required LocalDataDirProvider dirs,
    CoreAssetFetcher? fetcher,
    HashVerifier? hashes,
    bool Function()? isIOS,
    bool Function()? isCancelled,
    this.maxBytes = maxAssetBytes,
  })  : _dirProvider = dirs,
        _fetcher = fetcher ?? const HttpClientAssetFetcher(),
        _hashes = hashes ?? const PlatformHashVerifier(),
        _isIOS = isIOS ?? _platformIsIOS,
        _isCancelledOverride = isCancelled;

  static bool _platformIsIOS() => Platform.isIOS;

  /// Refuse absurd payloads before hashing (largest shipped core ~170 MB).
  static const int maxAssetBytes = 512 * 1024 * 1024;

  final LocalDataDirProvider _dirProvider;
  final CoreAssetFetcher _fetcher;
  final HashVerifier _hashes;
  final bool Function() _isIOS;
  final bool Function()? _isCancelledOverride;

  /// Size cap for one streamed asset. Tests lower it; production uses
  /// [maxAssetBytes].
  final int maxBytes;

  final CoreDownloadCancel _cancel = CoreDownloadCancel();

  bool get _isCancelled => _isCancelledOverride?.call() ?? _cancel.isCancelled;

  /// Clears a previous cancellation before starting a new download.
  void resetCancellation() => _cancel.reset();

  /// Requests cancellation; polled before and while bytes stream in.
  void cancelDownload() => _cancel.cancel();

  static void _deleteIfExists(File file) {
    if (!file.existsSync()) return;
    try {
      file.deleteSync();
    } catch (_) {}
  }

  /// Fetches, verifies, stages, and installs one core.
  /// Returns the verified pin on success; throws [CoreDownloadException]
  /// otherwise.
  Future<String> download({
    required CoreManifest manifest,
    required CoreRelease release,
    required String platformKey,
    required CoreRegistry registry,
  }) async {
    if (_isIOS()) {
      throw StateError('iOS never downloads cores (App Review 2.5.2/4.7)');
    }
    if (manifest.blocked) {
      throw StateError(
        '${manifest.name} is on hold: ${manifest.blockedReason}',
      );
    }
    final osKey = platformKey.split('-').first;
    if (manifest.delivery[osKey] != 'download') {
      throw StateError(
        '${manifest.id} is not a downloadable core on $osKey',
      );
    }
    final pin = manifest.artifacts[platformKey]?.toLowerCase();
    if (pin == null) {
      throw StateError(
        'No pinned artifact for ${manifest.id} on $platformKey',
      );
    }
    if (_isCancelled) {
      throw CoreDownloadException(CoreDownloadFailure.cancelled);
    }
    // Throws when nothing is published for this pair (honest UI message).
    final urls = <Uri>[release.downloadUri(platformKey, manifest.id)];
    final fallback = release.fallbackUri(platformKey, manifest.id);
    if (fallback != null) urls.add(fallback);

    final ext = platformKey.startsWith('windows')
        ? 'dll'
        : (platformKey.startsWith('macos') || platformKey.startsWith('ios'))
            ? 'dylib'
            : 'so';
    final dir = await _dirProvider.localDataDir();
    final coreDir = Directory('${dir.path}/cores/${manifest.id}');
    await coreDir.create(recursive: true);
    final dest = File('${coreDir.path}/${manifest.id}.$ext');
    final part = File('${dest.path}.part');
    _deleteIfExists(part);

    var fetched = false;
    for (var attempt = 0; attempt < urls.length; attempt++) {
      final url = urls[attempt];
      final lastAttempt = attempt == urls.length - 1;
      if (_isCancelled) {
        _deleteIfExists(part);
        throw CoreDownloadException(
          CoreDownloadFailure.cancelled,
          'Stopped before fetching $url',
        );
      }
      var received = 0;
      var sink = part.openWrite();
      try {
        await for (final chunk in _fetcher.open(url)) {
          if (_isCancelled) {
            throw CoreDownloadException(
              CoreDownloadFailure.cancelled,
              'Stopped while fetching $url',
            );
          }
          received += chunk.length;
          if (received > maxBytes) {
            throw CoreDownloadException(
              CoreDownloadFailure.tooLarge,
              'Core asset larger than $maxBytes bytes — refusing '
              '${manifest.id}',
            );
          }
          sink.add(chunk);
        }
        await sink.flush();
        await sink.close();
        fetched = true;
        break;
      } catch (e) {
        try {
          await sink.close();
        } catch (_) {}
        _deleteIfExists(part);
        if (e is CoreDownloadException) rethrow;
        final status = e is CoreAssetHttpException ? e.statusCode : null;
        final missing =
            status == HttpStatus.notFound ||
            (e is StateError && e.message.contains('HTTP 404'));
        if (missing && !lastAttempt) {
          // The configured repository is a stale owner; retry once against
          // the current one. The pin gate below still applies to its bytes.
          continue;
        }
        final tried = urls
            .take(attempt + 1)
            .map((u) => u.toString())
            .join(', then ');
        final why = status == null ? '$e' : 'HTTP $status';
        throw CoreDownloadException(
          CoreDownloadFailure.unreachable,
          'Tried $tried — $why',
        );
      }
    }
    if (!fetched) {
      throw CoreDownloadException(CoreDownloadFailure.unreachable);
    }

    if (!await verifyPinnedFile(part.path, pin, hashes: _hashes)) {
      _deleteIfExists(part);
      _deleteIfExists(File('${part.path}.ezpin'));
      throw CoreDownloadException(
        CoreDownloadFailure.checksumMismatch,
        'SHA-256 mismatch for ${manifest.id} — download discarded',
      );
    }

    _deleteIfExists(dest);
    _deleteIfExists(File('${dest.path}.ezpin'));
    part.renameSync(dest.path);
    // Carry the verified sidecar across the rename (rename preserves
    // mtime/size, so its record still matches the destination).
    final partSidecar = File('${part.path}.ezpin');
    final destSidecar = File('${dest.path}.ezpin');
    if (partSidecar.existsSync()) {
      partSidecar.renameSync(destSidecar.path);
    } else {
      final stat = dest.statSync();
      destSidecar.writeAsStringSync(
        json.encode({
          'pin': pin,
          'size': stat.size,
          'mtimeMs': stat.modified.millisecondsSinceEpoch,
        }),
      );
    }

    registry.install(manifest, expectedSha256: pin);
    return pin;
  }
}
